// Offline generation from the pinned, licensed GeoJSON and reviewed ACC calibration.
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
const dir=resolve(import.meta.dirname,'../assets/track-maps');
const raw=await readFile(resolve(dir,'monza-source.json'));
if(createHash('sha256').update(raw).digest('hex')!=='8b0758ef5a52bb9360c7673d45e0fbea6f29f7349486c5acbb2fe9aa340cb495')throw Error('Unreviewed Monza source');
const geo=JSON.parse(raw).features[0];
if(geo.properties.id!=='it-1922'||geo.geometry.type!=='LineString')throw Error('Unexpected circuit');
const calibration=JSON.parse(await readFile(resolve(dir,'monza-calibration.json'),'utf8'));
const {origin,metric,worldToGps,worldOffset}=calibration;
const gps=geo.geometry.coordinates.map(([lon,lat])=>[(lon-origin[0])*metric[0],(lat-origin[1])*metric[1]]);
// First straight points left. The rest of the circuit lies above it, as in the reference.
const angle=Math.atan2(gps[1][1]-gps[0][1],gps[1][0]-gps[0][0]);
const display=[[-Math.cos(angle),-Math.sin(angle)],[-Math.sin(angle),Math.cos(angle)]];
const multiply=(p,m)=>[p[0]*m[0][0]+p[1]*m[1][0],p[0]*m[0][1]+p[1]*m[1][1]];
const oriented=gps.map(p=>multiply(p,display));
const lo=[0,1].map(i=>Math.min(...oriented.map(p=>p[i])));
const hi=[0,1].map(i=>Math.max(...oriented.map(p=>p[i])));
const scale=Math.min(840/(hi[0]-lo[0]),400/(hi[1]-lo[1]));
const offset=[(1000-(hi[0]-lo[0])*scale)/2,80];
const project=p=>p.map((v,i)=>offset[i]+(v-lo[i])*scale);
const round=v=>Number(v.toFixed(5));
const matrix=worldToGps.map(row=>multiply(row,display).map(v=>round(v*scale)));
const translation=project(multiply(worldOffset,display)).map(round);
const points=oriented.map(p=>project(p).map(round));
const map={id:'monza-gp',version:'20261024-geojson-r1',viewBox:[0,0,1000,600],
 source:{url:'https://github.com/bacinger/f1-circuits',revision:'8094e957b8d6aa8b9f4510c93968556cccd30e02',file:'circuits/it-1922.geojson',license:'MIT',copyright:'2019–2025 Tomislav Bacinger'},
 points,worldToMap:matrix,worldOffset:translation,
 labels:[
  {text:'Curve di Lesmo',x:165,y:49,anchor:'middle'},
  {text:'Variante della Roggia',lines:['Variante della','Roggia'],x:192,y:260,anchor:'start',secondary:true},
  {text:'Curva Grande',x:234,y:363,anchor:'start',secondary:true},
  {text:'Variante del Rettifilo',x:392,y:529,anchor:'middle'},
  {text:'Variante Ascari',x:545,y:333,anchor:'start'},
  {text:'Curva Parabolica',x:870,y:354,anchor:'middle'}]};
await writeFile(resolve(dir,'monza.js'),'// Generated by scripts/generate-monza-map.mjs. See LICENSE.txt and monza-calibration.json.\nexport const MONZA_MAP = '+JSON.stringify(map,null,2)+';\n');
console.log(`Generated Monza GP: ${points.length} fixed points; ACC world calibration preserved.`);
