import {readFile, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {timingMarksForSegments} from './track-map-timing.mjs';

const directory = resolve(import.meta.dirname, '../assets/track-maps');
const read = async name => JSON.parse(await readFile(resolve(directory, name), 'utf8'));
const {sourceUrl, tracks} = await read('race-control-source.json');
const calibrations = await read('race-control-calibration.json');
const source = {url: sourceUrl, credit: 'ACC Race Control · MIT'};
const viewBox = [0, 0, 1000, 600];
const round = value => Number(value.toFixed(2));
const multiply = ([x, y], matrix) => [
  x * matrix[0][0] + y * matrix[1][0], x * matrix[0][1] + y * matrix[1][1]
];

function fitToViewBox(points) {
  const min = [0, 1].map(axis => Math.min(...points.map(point => point[axis])));
  const max = [0, 1].map(axis => Math.max(...points.map(point => point[axis])));
  const size = max.map((value, axis) => value - min[axis]);
  const scale = Math.min(840 / size[0], 440 / size[1]);
  const padding = size.map((value, axis) => (viewBox[axis + 2] - value * scale) / 2);
  return {
    points: points.map(point => point.map((value, axis) => (value - min[axis]) * scale + padding[axis])),
    scale,
    offset: padding.map((value, axis) => value - min[axis] * scale)
  };
}

function mapData(code, track, points) {
  const steps = track.points.length - 1;
  const measuredGap = Math.hypot(...track.points.at(-1));
  const [s1, s2, finish] = track.sectorSplines;
  if (steps !== 200 || track.points[0].some(value => value !== 0) ||
      measuredGap > track.reportedTrackMeters / steps ||
      Math.abs(measuredGap - track.closureGapMeters) > 0.01 ||
      !(0 < s1 && s1 < s2 && s2 < finish && finish === 1)) {
    throw new Error(`Unexpected Race Control geometry for ${code}`);
  }
  // RC records one step per 1/200 of a lap. The S3 boundary at 1 wraps to start/finish.
  const timingSegments = [0, s1, s2].map(spline => {
    const sample = spline * steps;
    return [Math.floor(sample), sample % 1];
  });
  return {id: code, viewBox, points: points.map(point => point.map(round)),
    timingMarks: timingMarksForSegments(points, timingSegments), source};
}

const {origin, metric, worldToGps, worldOffset, raceControlDisplay} = await read('monza-calibration.json');
const {localToMap, localOffset} = raceControlDisplay;
const monza = mapData('monza-gp', tracks.monza, tracks.monza.points.map(point =>
  multiply(point, localToMap).map((value, axis) => value + localOffset[axis])));

// Keep Monza's existing ACC-to-SVG projection in the display frame used for the RC fit.
const reference = (await read('monza-source.json')).features[0].geometry.coordinates
  .map(point => point.map((value, axis) => (value - origin[axis]) * metric[axis]));
const angle = Math.atan2(reference[1][1] - reference[0][1], reference[1][0] - reference[0][0]);
const cos = Math.cos(angle), sin = Math.sin(angle);
const display = [[-cos, -sin], [-sin, cos]];
const oriented = reference.map(point => multiply(point, display));
const min = [0, 1].map(axis => Math.min(...oriented.map(point => point[axis])));
const size = min.map((value, axis) => Math.max(...oriented.map(point => point[axis])) - value);
const scale = Math.min(840 / size[0], 400 / size[1]);
const offset = [(1000 - size[0] * scale) / 2, 80];
const roundProjection = value => Number(value.toFixed(5));
monza.worldToMap = worldToGps.map(row => multiply(row, display).map(value => roundProjection(value * scale)));
monza.worldOffset = multiply(worldOffset, display).map((value, axis) =>
  roundProjection(offset[axis] + (value - min[axis]) * scale));
monza.labels = [
  {text:'Curve di Lesmo', x:165, y:49, anchor:'middle'},
  {text:'Variante della Roggia', lines:['Variante della','Roggia'], x:192, y:260, anchor:'start', secondary:true},
  {text:'Curva Grande', x:234, y:363, anchor:'start', secondary:true},
  {text:'Variante del Rettifilo', x:392, y:529, anchor:'middle'},
  {text:'Variante Ascari', x:545, y:333, anchor:'start'},
  {text:'Curva Parabolica', x:870, y:354, anchor:'middle'}
];

const header = '// Generated by scripts/generate-race-control-maps.mjs. See race-control-LICENSE.txt.\n';
const additional = Object.entries(tracks).filter(([code]) => code !== 'monza').map(([code, track]) => {
  const {points, scale, offset} = fitToViewBox(track.points);
  const map = mapData(code, track, points);
  const calibration = calibrations[code];
  if (calibration) {
    const roundProjection = value => Number(value.toFixed(8));
    map.worldToMap = calibration.worldToLocal.map(row => row.map(value => roundProjection(value * scale)));
    map.worldOffset = calibration.localOffset.map((value, axis) => roundProjection(value * scale + offset[axis]));
  }
  return `  ${JSON.stringify(code)}: ${JSON.stringify(map)}`;
});
await writeFile(resolve(directory, 'monza.js'), header + `export const MONZA_MAP = ${JSON.stringify(monza)};\n`);
await writeFile(resolve(directory, 'race-control.js'), header +
  `export const RACE_CONTROL_MAPS = {\n${additional.join(',\n')}\n};\n`);
