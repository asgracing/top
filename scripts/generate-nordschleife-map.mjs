// Offline generation from the user-supplied pinned GeoJSON and reviewed ACC coordinates.
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
const dir=resolve(import.meta.dirname,'../assets/track-maps');
const raw=await readFile(resolve(dir,'nurburgring_24h-source.json'));
const hash=createHash('sha256').update(raw).digest('hex');
const expected='3211a528a629247edbfb8bb9e3c908bad668f7825e44f033994ae01d493f5c9f';
if(hash!==expected)throw Error('Unreviewed Nürburgring 24h source');
const source=JSON.parse(raw);
if(source.features?.length!==1||source.features[0].geometry.type!=='LineString')throw Error('Unexpected circuit');
const {origin,metric,worldToGps,worldOffset,calibration}=JSON.parse(await readFile(resolve(dir,'nurburgring_24h-calibration.json'),'utf8'));
if(calibration.checks.some(c=>c.p95_metres>30))throw Error('Calibration exceeds reviewed tolerance');
const metricPoints=source.features[0].geometry.coordinates.map(([lon,lat])=>[(lon-origin[0])*metric[0],(lat-origin[1])*metric[1]]);
// Preserve the reference's north-up view: GP bottom left, Nordschleife above/right.
// Simplify in metres, preserving bends to within one metre, before display scaling.
const segmentDistance=(p,a,b)=>{
 const v=b.map((x,i)=>x-a[i]),w=p.map((x,i)=>x-a[i]);
 const t=Math.max(0,Math.min(1,(w[0]*v[0]+w[1]*v[1])/(v[0]*v[0]+v[1]*v[1]||1)));
 return Math.hypot(w[0]-t*v[0],w[1]-t*v[1]);
};
function simplify(points){
 if(points.length<3)return points;
 let distance=0,index=0;
 for(let i=1;i<points.length-1;i++){
  const d=segmentDistance(points[i],points[0],points.at(-1));
  if(d>distance){distance=d;index=i;}
 }
 if(distance<=1)return [points[0],points.at(-1)];
 return [...simplify(points.slice(0,index+1)).slice(0,-1),...simplify(points.slice(index))];
}
const northUp=metricPoints.map(([x,y])=>[x,-y]);
const lo=[0,1].map(i=>Math.min(...northUp.map(p=>p[i]))),hi=[0,1].map(i=>Math.max(...northUp.map(p=>p[i])));
const scale=Math.min(1000/(hi[0]-lo[0]),900/(hi[1]-lo[1]));
const round=v=>Number(v.toFixed(5));
const project=([x,y])=>[round(100+(x-lo[0])*scale),round(70+(-y-lo[1])*scale)];
const reduced=simplify(metricPoints).slice(0,-1);
const map={id:'nurburgring-24h',version:'20261027-geojson-r1',viewBox:[0,0,1200,1050],
 source:{url:'https://github.com/R1naldinho/TracksGEOJSON',revision:'3f984b3d67a115eb6fc9a6727ac3c1171449a420',file:'nurburgring24h.geojson',sha256:hash,license:null,credit:'R1naldinho · TracksGEOJSON',note:'User-supplied source. Upstream has no license file; no MIT license is asserted for this asset.',originalPoints:metricPoints.length,simplificationMetres:1},
 points:reduced.map(project),worldToMap:worldToGps.map(([x,y])=>[round(x*scale),round(-y*scale)]),worldOffset:project(worldOffset),labels:[]};
await writeFile(resolve(dir,'nurburgring_24h.js'),'// Generated by scripts/generate-nordschleife-map.mjs. Source attribution is in this module.\nexport const NURBURGRING_24H_MAP = '+JSON.stringify(map,null,2)+';\n');
console.log(`Nürburgring 24h: ${metricPoints.length} source vertices → ${map.points.length} fixed points (1 m tolerance).`);
