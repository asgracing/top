// Offline generation from pinned MIT GeoJSON and reviewed independent ACC laps.
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
const dir=resolve(import.meta.dirname,'../assets/track-maps');
const raw=await readFile(resolve(dir,'spa-source.json'));
if(createHash('sha256').update(raw).digest('hex')!=='b867de9cc8364cc9b545a044377a56a697b8db77823c849c1a1c03760a943381')throw Error('Unreviewed Spa source');
const geo=JSON.parse(raw).features[0];
if(geo.properties.id!=='be-1925'||geo.geometry.type!=='LineString')throw Error('Unexpected circuit');
const {origin,metric,worldToGps,worldOffset}=JSON.parse(await readFile(resolve(dir,'spa-calibration.json'),'utf8'));
const gps=geo.geometry.coordinates.map(([lon,lat])=>[(lon-origin[0])*metric[0],(lat-origin[1])*metric[1]]);
// User reference: La Source bottom left; Les Combes top; Bruxelles top right.
// GPS north is reflected with the same transform applied to the ACC positions.
const angle=-105.3*Math.PI/180;
const display=[[Math.cos(angle),Math.sin(angle)],[Math.sin(angle),-Math.cos(angle)]];
const multiply=(p,m)=>[p[0]*m[0][0]+p[1]*m[1][0],p[0]*m[0][1]+p[1]*m[1][1]];
const oriented=gps.map(p=>multiply(p,display));
const lo=[0,1].map(i=>Math.min(...oriented.map(p=>p[i])));
const hi=[0,1].map(i=>Math.max(...oriented.map(p=>p[i])));
const scale=Math.min(960/(hi[0]-lo[0]),760/(hi[1]-lo[1]));
const offset=[100,70];
const project=p=>p.map((v,i)=>offset[i]+(v-lo[i])*scale);
const round=v=>Number(v.toFixed(7));
const map={id:'spa-gp',version:'20261026-geojson-r1',viewBox:[0,0,1200,900],
 source:{url:'https://github.com/bacinger/f1-circuits',revision:'8094e957b8d6aa8b9f4510c93968556cccd30e02',file:'circuits/be-1925.geojson',license:'MIT',copyright:'2019–2025 Tomislav Bacinger'},
 points:oriented.map(p=>project(p).map(round)),
 worldToMap:worldToGps.map(row=>multiply(row,display).map(v=>round(v*scale))),
 worldOffset:project(multiply(worldOffset,display)).map(round),
 labels:[
  {text:'La Source',x:110,y:860,anchor:'start'},
  {text:'Eau Rouge',x:210,y:470,anchor:'end'},
  {text:'Raidillon',x:310,y:380,anchor:'middle'},
  {text:'Kemmel',x:420,y:250,anchor:'middle'},
  {text:'Les Combes',x:730,y:42,anchor:'end'},
  {text:'Malmedy',x:910,y:40,anchor:'start'},
  {text:'Bruxelles',x:1030,y:255,anchor:'middle'},
  {text:'Double Gauche',x:730,y:350,anchor:'start'},
  {text:'Les Fagnes',x:980,y:460,anchor:'start'},
  {text:'Campus',x:1010,y:565,anchor:'end',secondary:true},
  {text:'Paul Frère',x:1040,y:780,anchor:'middle'},
  {text:'Blanchimont',x:650,y:558,anchor:'middle'},
  {text:'Chicane',x:355,y:650,anchor:'start'}]};
await writeFile(resolve(dir,'spa.js'),'// Generated by scripts/generate-spa-map.mjs. See LICENSE.txt and spa-calibration.json.\nexport const SPA_MAP = '+JSON.stringify(map,null,2)+';\n');
console.log(`Generated Spa GP: ${map.points.length} fixed points; ACC world calibration preserved.`);
